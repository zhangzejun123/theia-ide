"""
迁移 node_modules：
1. 清空旧版 node_modules（保留特定文件/文件夹）
2. 将 build-cache-all/node_modules/ 中的所有内容拷贝过去
"""

import os
import re
import shutil

# ── 配置 ──────────────────────────────────────────────────────────────────────

# 旧版 node_modules 的位置（相对于本脚本，或改为绝对路径）
SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
OLD_NODE_MODULES = os.path.join(SCRIPT_DIR, "..", "node_modules")

# build-cache-all/node_modules 的位置
BUILD_CACHE_NODE_MODULES = os.path.join(SCRIPT_DIR, "..", "build-cache-all", "node_modules")

# ── 保留规则 ──────────────────────────────────────────────────────────────────

# 始终保留的文件夹名
KEEP_DIRS = {".git"}

# 始终保留的文件名（精确匹配）
KEEP_FILES_EXACT = {".gitignore", ".yarn-integrity"}

# 保留的文件名正则（CHANGELOG / README，支持 .md / .rst）
KEEP_FILES_PATTERN = re.compile(
    r"^(CHANGELOG|README)\.(md|rst)$", re.IGNORECASE
)

# ─────────────────────────────────────────────────────────────────────────────


def should_keep(name: str, is_dir: bool) -> bool:
    if is_dir:
        return name in KEEP_DIRS
    return name in KEEP_FILES_EXACT or bool(KEEP_FILES_PATTERN.match(name))


def clean_node_modules(target: str) -> None:
    print(f"清空 node_modules: {target}")
    for name in os.listdir(target):
        full = os.path.join(target, name)
        is_dir = os.path.isdir(full) and not os.path.islink(full)
        if should_keep(name, is_dir):
            print(f"  保留: {name}")
            continue
        if is_dir:
            shutil.rmtree(full)
        else:
            os.remove(full)
        print(f"  删除: {name}")


def copy_node_modules(src: str, dst: str) -> None:
    print(f"\n拷贝 {src} -> {dst}")
    for name in os.listdir(src):
        s = os.path.join(src, name)
        d = os.path.join(dst, name)
        if os.path.islink(s):
            link_target = os.readlink(s)
            if os.path.exists(d) or os.path.islink(d):
                os.remove(d)
            os.symlink(link_target, d)
            print(f"  链接: {name} -> {link_target}")
        elif os.path.isdir(s):
            shutil.copytree(s, d, symlinks=True, dirs_exist_ok=True)
            print(f"  目录: {name}")
        else:
            shutil.copy2(s, d)
            print(f"  文件: {name}")


def main() -> None:
    old = os.path.normpath(OLD_NODE_MODULES)
    src = os.path.normpath(BUILD_CACHE_NODE_MODULES)

    if not os.path.isdir(old):
        raise FileNotFoundError(f"旧版 node_modules 不存在: {old}")
    if not os.path.isdir(src):
        raise FileNotFoundError(f"build-cache-all/node_modules 不存在: {src}")

    clean_node_modules(old)
    copy_node_modules(src, old)
    print("\n迁移完成。")


if __name__ == "__main__":
    main()
