"""
迁移 node_modules（多线程版本）：
1. 清空旧版 node_modules（保留特定文件/文件夹）
2. 将 build-cache-all/node_modules/ 中的所有内容拷贝过去
"""

import os
import re
import shutil
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from threading import Lock
from datetime import datetime

# ── 配置 ──────────────────────────────────────────────────────────────────────

# 旧版 node_modules 的位置
OLD_NODE_MODULES = r"D:\gitlab\eclipse-theia"

# build-cache-all/node_modules 的位置
BUILD_CACHE_NODE_MODULES = r"D:\build-cache-all\node_modules"

# 线程数
MAX_WORKERS = 8

# ── 保留规则 ──────────────────────────────────────────────────────────────────

KEEP_DIRS = {".git"}
KEEP_FILES_EXACT = {".gitignore"}
KEEP_FILES_PATTERN = re.compile(r"^(CHANGELOG|README)\.(md|rst)$", re.IGNORECASE)

# ─────────────────────────────────────────────────────────────────────────────

print_lock = Lock()


def safe_print(msg: str) -> None:
    with print_lock:
        print(msg)


def should_keep(name: str, is_dir: bool) -> bool:
    if is_dir:
        return name in KEEP_DIRS
    return name in KEEP_FILES_EXACT or bool(KEEP_FILES_PATTERN.match(name))


def delete_item(full: str, name: str, is_dir: bool) -> tuple[str, bool]:
    """删除单个文件/目录，返回 (名称, 是否成功)"""
    try:
        if is_dir:
            shutil.rmtree(full)
        else:
            os.remove(full)
        return (name, True)
    except Exception as e:
        safe_print(f"  删除失败: {name} - {e}")
        return (name, False)


def copy_item(s: str, d: str, name: str) -> tuple[str, bool]:
    """拷贝单个文件/目录，返回 (名称, 是否成功)"""
    try:
        if os.path.islink(s):
            link_target = os.readlink(s)
            if os.path.exists(d) or os.path.islink(d):
                os.remove(d)
            os.symlink(link_target, d)
            return (f"{name} -> {link_target}", True)
        elif os.path.isdir(s):
            shutil.copytree(s, d, symlinks=True, dirs_exist_ok=True)
            return (name, True)
        else:
            shutil.copy2(s, d)
            return (name, True)
    except Exception as e:
        safe_print(f"  拷贝失败: {name} - {e}")
        return (name, False)


def clean_node_modules(target: str) -> None:
    safe_print(f"清空 node_modules: {target}")

    items = []
    for name in os.listdir(target):
        full = os.path.join(target, name)
        is_dir = os.path.isdir(full) and not os.path.islink(full)
        if should_keep(name, is_dir):
            safe_print(f"  保留: {name}")
            continue
        items.append((full, name, is_dir))

    if not items:
        safe_print("  无需删除")
        return

    safe_print(f"  开始删除 {len(items)} 个项目...")

    deleted = 0
    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        futures = {
            executor.submit(delete_item, full, name, is_dir): name
            for full, name, is_dir in items
        }
        for future in as_completed(futures):
            name, success = future.result()
            if success:
                deleted += 1

    safe_print(f"  已删除 {deleted}/{len(items)} 个项目")


def copy_node_modules(src: str, dst: str) -> dict:
    """拷贝并返回统计信息：copied数、总时间"""
    safe_print(f"\n拷贝 {src} -> {dst}")

    items = []
    for name in os.listdir(src):
        s = os.path.join(src, name)
        d = os.path.join(dst, name)
        items.append((s, d, name))

    if not items:
        safe_print("  无需拷贝")
        return {"copied": 0, "total": 0, "time_sec": 0.0}

    safe_print(f"  开始拷贝 {len(items)} 个项目...")

    start_time = time.time()
    copied = 0
    with ThreadPoolExecutor(max_workers=MAX_WORKERS) as executor:
        futures = {
            executor.submit(copy_item, s, d, name): name
            for s, d, name in items
        }
        for future in as_completed(futures):
            _, success = future.result()
            if success:
                copied += 1

    elapsed = time.time() - start_time
    safe_print(f"  已拷贝 {copied}/{len(items)} 个项目，耗时 {elapsed:.2f}s")

    return {"copied": copied, "total": len(items), "time_sec": elapsed}


def main() -> None:
    old = os.path.normpath(OLD_NODE_MODULES)
    src = os.path.normpath(BUILD_CACHE_NODE_MODULES)

    if not os.path.isdir(old):
        raise FileNotFoundError(f"旧版 node_modules 不存在: {old}")
    if not os.path.isdir(src):
        raise FileNotFoundError(f"build-cache-all/node_modules 不存在: {src}")

    clean_node_modules(old)
    stats = copy_node_modules(src, old)
    safe_print("\n迁移完成。")

    # 写日志文件
    timestamp = datetime.now().strftime("%Y-%m-%d_%H-%M-%S")
    log_file = os.path.join(os.path.dirname(os.path.abspath(__file__)), f"migrate_{timestamp}.log")
    with open(log_file, "w", encoding="utf-8") as f:
        f.write(f"时间戳: {timestamp}\n")
        f.write(f"源目录: {src}\n")
        f.write(f"目标目录: {old}\n")
        f.write(f"拷贝数量: {stats['copied']}/{stats['total']}\n")
        f.write(f"耗时: {stats['time_sec']:.2f} 秒\n")

    safe_print(f"日志已保存: {log_file}")


if __name__ == "__main__":
    main()